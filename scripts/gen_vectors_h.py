#!/usr/bin/env python3
"""gen_vectors_h.py - turn spec/vectors.json into firmware/test/test_wire/vectors.h.

Why: the test vectors live in ONE place (spec/vectors.json). The C test needs them
as arrays, so this script writes the header. Never edit vectors.h by hand.

Run (from the repo root):  python3 scripts/gen_vectors_h.py
Check only (exit 1 if vectors.h is out of date):  python3 scripts/gen_vectors_h.py --check
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "spec" / "vectors.json"
DST = ROOT / "firmware" / "test" / "test_wire" / "vectors.h"


def c_bytes(hex_text: str) -> str:
    """'e803' -> '{ 0xe8, 0x03 }'. An empty payload becomes '{ 0x00 }' (C forbids empty arrays)."""
    raw = bytes.fromhex(hex_text) or b"\x00"
    return "{ " + ", ".join(f"0x{b:02x}" for b in raw) + " }"


def render(doc: dict) -> str:
    out = []
    w = out.append
    w("/* GENERATED by scripts/gen_vectors_h.py from spec/vectors.json. DO NOT EDIT. */")
    w("#ifndef VECTORS_H")
    w("#define VECTORS_H")
    w("#include <stddef.h>")
    w("#include <stdint.h>")
    w("")
    w("typedef struct { const uint8_t *in; size_t in_len; const uint8_t *out; size_t out_len; } cobs_vec_t;")
    w("typedef struct {")
    w("    const char *name; uint8_t type, msg; uint16_t seq, ack;")
    w("    const uint8_t *payload; size_t payload_len; const uint8_t *wire; size_t wire_len;")
    w("} frame_vec_t;")
    w("")
    for i, v in enumerate(doc["cobs"]):
        w(f"static const uint8_t cobs_in_{i}[] = {c_bytes(v['in'])};")
        w(f"static const uint8_t cobs_out_{i}[] = {c_bytes(v['out'])};")
    w("static const cobs_vec_t COBS_VECTORS[] = {")
    for i, v in enumerate(doc["cobs"]):
        w(f"    {{ cobs_in_{i}, {len(v['in']) // 2}, cobs_out_{i}, {len(v['out']) // 2} }},")
    w("};")
    w(f"#define COBS_VECTOR_COUNT {len(doc['cobs'])}")
    w("")
    for i, f in enumerate(doc["frames"]):
        w(f"static const uint8_t frame_payload_{i}[] = {c_bytes(f['payload'])};")
        w(f"static const uint8_t frame_wire_{i}[] = {c_bytes(f['wire'])};")
    w("static const frame_vec_t FRAME_VECTORS[] = {")
    for i, f in enumerate(doc["frames"]):
        w(f"    {{ \"{f['name']}\", {f['type']}, {f['msg']}, {f['seq']}, {f['ack']}, "
          f"frame_payload_{i}, {len(f['payload']) // 2}, frame_wire_{i}, {len(f['wire']) // 2} }},")
    w("};")
    w(f"#define FRAME_VECTOR_COUNT {len(doc['frames'])}")
    w("")
    w(f"#define CRC16_CHECK_VALUE 0x{doc['crc16']['check']}u")
    w("#endif /* VECTORS_H */")
    return "\n".join(out) + "\n"


def main() -> int:
    text = render(json.loads(SRC.read_text()))
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text() != text:
            print("vectors.h is out of date: run scripts/gen_vectors_h.py")
            return 1
        print("vectors.h is up to date")
        return 0
    DST.write_text(text)
    print(f"wrote {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
